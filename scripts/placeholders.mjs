// Makes a tiny blurred preview of every image in public/images and writes them to
// src/content/placeholders.ts. Each preview is an SVG that blurs a 24px-wide WebP, about a
// kilobyte, set as the <img>'s background so something shows before the image arrives.
//
//   npm run placeholders      (run it again whenever an image is added or replaced)
import sharp from "sharp";
import { readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

const dir = "public/images";
const out = "src/content/placeholders.ts";
const width = 24;

const files = (await readdir(dir)).filter((f) => /\.(webp|png|jpe?g)$/i.test(f)).sort();
const entries = [];
for (const file of files) {
  const { data, info } = await sharp(join(dir, file))
    .resize({ width, withoutEnlargement: true })
    .webp({ quality: 50 })
    .toBuffer({ resolveWithObject: true });
  const { width: w, height: h } = info;
  // The blur is set in the SVG's own units, so it scales with the image. The alpha step keeps
  // the edges opaque instead of fading into the background.
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}" preserveAspectRatio="none">` +
    `<filter id="b" color-interpolation-filters="sRGB"><feGaussianBlur stdDeviation="1.4"/>` +
    `<feComponentTransfer><feFuncA type="discrete" tableValues="1 1"/></feComponentTransfer></filter>` +
    `<image width="100%" height="100%" preserveAspectRatio="none" filter="url(#b)" href="data:image/webp;base64,${data.toString("base64")}"/></svg>`;
  entries.push([`/images/${file}`, `url("data:image/svg+xml;base64,${Buffer.from(svg).toString("base64")}")`]);
}

const body = entries.map(([src, url]) => `  ${JSON.stringify(src)}:\n    ${JSON.stringify(url)},`).join("\n");
await writeFile(
  out,
  `// Generated by scripts/placeholders.mjs. Do not edit; run \`npm run placeholders\` instead.\n\n` +
    `/** A blurred preview of each image, as a CSS background-image value. */\n` +
    `export const placeholders: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`Wrote ${entries.length} placeholders to ${out}`);
